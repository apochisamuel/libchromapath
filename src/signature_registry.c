size_t cp_signature_registry_count(void) {
    return sizeof(cp_signatures) / sizeof(cp_signatures[0]);
}

cp_status cp_signature_registry_at(size_t index, cp_signature_info *out) {
    if (!out) return CP_ERR_ARGUMENT;
    if (index >= cp_signature_registry_count()) return CP_ERR_NOT_FOUND;
    *out = cp_signatures[index];
    return CP_OK;
}

const char *cp_signature_name(uint32_t signature) {
    for (size_t i = 0; i < cp_signature_registry_count(); ++i) {
        if (cp_signatures[i].signature == signature) return cp_signatures[i].name;
    }
    return "Unknown signature";
}

cp_signature_group cp_signature_group_of(uint32_t signature) {
    for (size_t i = 0; i < cp_signature_registry_count(); ++i) {
        if (cp_signatures[i].signature == signature) return cp_signatures[i].group;
    }
    return CP_SIGNATURE_UNKNOWN;
}
