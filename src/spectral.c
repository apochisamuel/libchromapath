static double cp_cmf_component(double wavelength_nm, int component) {
    if (wavelength_nm < 360.0 || wavelength_nm > 830.0) return 0.0;
    double position = wavelength_nm - 360.0;
    size_t lower = (size_t)floor(position);
    size_t upper = lower + 1;
    if (upper >= sizeof(cp_cmf_table) / sizeof(cp_cmf_table[0])) upper = lower;
    double amount = position - (double)lower;
    double left;
    double right;
    if (component == 0) {
        left = cp_cmf_table[lower].x;
        right = cp_cmf_table[upper].x;
    } else if (component == 1) {
        left = cp_cmf_table[lower].y;
        right = cp_cmf_table[upper].y;
    } else {
        left = cp_cmf_table[lower].z;
        right = cp_cmf_table[upper].z;
    }
    return cp_interpolate_linear(left, right, amount);
}

double cp_cie1931_x(double wavelength_nm) {
    return cp_cmf_component(wavelength_nm, 0);
}

double cp_cie1931_y(double wavelength_nm) {
    return cp_cmf_component(wavelength_nm, 1);
}

double cp_cie1931_z(double wavelength_nm) {
    return cp_cmf_component(wavelength_nm, 2);
}

double cp_planck_spd(double wavelength_nm, double temperature_kelvin) {
    if (wavelength_nm <= 0.0 || temperature_kelvin <= 0.0) return 0.0;
    const double c1 = 3.741771852e-16;
    const double c2 = 1.438776877e-2;
    double wavelength_m = wavelength_nm * 1e-9;
    double denominator = pow(wavelength_m, 5.0) *
                         (exp(c2 / (wavelength_m * temperature_kelvin)) - 1.0);
    if (denominator <= 0.0 || !isfinite(denominator)) return 0.0;
    return c1 / denominator;
}

double cp_daylight_spd(double wavelength_nm, double correlated_temperature) {
    if (correlated_temperature < 4000.0 || correlated_temperature > 25000.0) return 0.0;
    double blackbody = cp_planck_spd(wavelength_nm, correlated_temperature);
    double blue = exp(-0.5 * pow((wavelength_nm - 460.0) / 55.0, 2.0));
    double broad = exp(-0.5 * pow((wavelength_nm - 560.0) / 180.0, 2.0));
    double factor = 0.86 + 0.18 * blue + 0.04 * broad;
    return blackbody * factor;
}

cp_status cp_spectral_interpolate(const cp_spectral_curve *curve,
                                  double wavelength_nm, double *out) {
    if (!curve || !curve->samples || curve->count == 0 || !out) return CP_ERR_ARGUMENT;
    if (wavelength_nm <= curve->samples[0].wavelength_nm) {
        *out = curve->samples[0].value;
        return CP_OK;
    }
    if (wavelength_nm >= curve->samples[curve->count - 1].wavelength_nm) {
        *out = curve->samples[curve->count - 1].value;
        return CP_OK;
    }
    size_t low = 0;
    size_t high = curve->count - 1;
    while (high - low > 1) {
        size_t middle = low + (high - low) / 2;
        if (curve->samples[middle].wavelength_nm <= wavelength_nm) low = middle;
        else high = middle;
    }
    double width = curve->samples[high].wavelength_nm - curve->samples[low].wavelength_nm;
    if (width <= 0.0) return CP_ERR_FORMAT;
    double amount = (wavelength_nm - curve->samples[low].wavelength_nm) / width;
    *out = cp_interpolate_linear(curve->samples[low].value,
                                 curve->samples[high].value, amount);
    return CP_OK;
}

cp_status cp_spectral_to_xyz(const cp_spectral_curve *reflectance,
                             const cp_spectral_curve *illuminant, cp_xyz *out) {
    if (!reflectance || !illuminant || !out) return CP_ERR_ARGUMENT;
    double X = 0.0;
    double Y = 0.0;
    double Z = 0.0;
    double normalizer = 0.0;
    for (double wavelength = 360.0; wavelength <= 830.0; wavelength += 1.0) {
        double r;
        double i;
        if (cp_spectral_interpolate(reflectance, wavelength, &r) != CP_OK) continue;
        if (cp_spectral_interpolate(illuminant, wavelength, &i) != CP_OK) continue;
        double y = cp_cie1931_y(wavelength);
        X += r * i * cp_cie1931_x(wavelength);
        Y += r * i * y;
        Z += r * i * cp_cie1931_z(wavelength);
        normalizer += i * y;
    }
    if (normalizer <= 0.0) return CP_ERR_FORMAT;
    out->x = X / normalizer;
    out->y = Y / normalizer;
    out->z = Z / normalizer;
    return CP_OK;
}
