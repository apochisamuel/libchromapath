static int cp_space_name_equal(const char *left, const char *right) {
    if (!left || !right) return 0;
    while (*left && *right) {
        unsigned char a = (unsigned char)*left++;
        unsigned char b = (unsigned char)*right++;
        if (tolower(a) != tolower(b)) return 0;
    }
    return *left == 0 && *right == 0;
}

size_t cp_rgb_working_space_count(void) {
    return sizeof(cp_working_spaces) / sizeof(cp_working_spaces[0]);
}

cp_status cp_rgb_working_space_at(size_t index, cp_rgb_working_space *out) {
    if (!out) return CP_ERR_ARGUMENT;
    if (index >= cp_rgb_working_space_count()) return CP_ERR_NOT_FOUND;
    *out = cp_working_spaces[index];
    return CP_OK;
}

cp_status cp_rgb_working_space_find(const char *name, cp_rgb_working_space *out) {
    if (!name || !out) return CP_ERR_ARGUMENT;
    for (size_t i = 0; i < cp_rgb_working_space_count(); ++i) {
        if (cp_space_name_equal(name, cp_working_spaces[i].name)) {
            *out = cp_working_spaces[i];
            return CP_OK;
        }
    }
    return CP_ERR_NOT_FOUND;
}

cp_status cp_rgb_working_space_matrix(const cp_rgb_working_space *space,
                                      cp_matrix3x3 *rgb_to_xyz,
                                      cp_matrix3x3 *xyz_to_rgb) {
    if (!space || !rgb_to_xyz || !xyz_to_rgb) return CP_ERR_ARGUMENT;
    cp_xyz red = cp_xyy_to_xyz(space->red);
    cp_xyz green = cp_xyy_to_xyz(space->green);
    cp_xyz blue = cp_xyy_to_xyz(space->blue);
    cp_xyz white = cp_xyy_to_xyz(space->white);
    cp_matrix3x3 primaries = {{{red.x, green.x, blue.x},
                               {red.y, green.y, blue.y},
                               {red.z, green.z, blue.z}}};
    cp_matrix3x3 inverse;
    cp_status status = cp_matrix3x3_inverse(primaries, &inverse);
    if (status != CP_OK) return status;
    cp_xyz scale = cp_matrix3x3_apply(inverse, white);
    cp_matrix3x3 matrix = {{{red.x * scale.x, green.x * scale.y, blue.x * scale.z},
                            {red.y * scale.x, green.y * scale.y, blue.y * scale.z},
                            {red.z * scale.x, green.z * scale.y, blue.z * scale.z}}};
    status = cp_matrix3x3_inverse(matrix, xyz_to_rgb);
    if (status != CP_OK) return status;
    *rgb_to_xyz = matrix;
    return CP_OK;
}
